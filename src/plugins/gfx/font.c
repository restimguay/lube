/* Anything else (and each character past ASCII): a box. */
static const char *const UNKNOWN = "#####" "#...#" "#...#" "#...#" "#...#" "#...#" "#####" ".....";

/* Draws text at (x, y), each font pixel a scale-by-scale square. */
static void draw_text(Canvas *c, const char *s, size_t n, int x, int y, uint32_t color, int scale) {
    int cx = x;
    for (size_t i = 0; i < n; i++) {
        unsigned char ch = (unsigned char)s[i];
        if (ch == '\n') {
            cx = x;
            y += LINE_H * scale;
            continue;
        }
        if ((ch & 0xC0) == 0x80) continue;  /* (the rest of a UTF-8 character: one box for it all) */
        const char *g = ch >= 32 && ch < 127 ? GLYPHS[ch - 32] : UNKNOWN;
        for (int row = 0; row < GLYPH_H; row++)
            for (int col = 0; col < GLYPH_W; col++)
                if (g[row * GLYPH_W + col] == '#') fill_rect(c, cx + col * scale, y + row * scale, scale, scale, color);
        cx += ADVANCE * scale;
    }
}

/* How much room text takes: its widest line, and its lines. */
static void text_size(const char *s, size_t n, int scale, int *w, int *h) {
    int lines = 1, cols = 0, widest = 0;
    for (size_t i = 0; i < n; i++) {
        unsigned char ch = (unsigned char)s[i];
        if (ch == '\n') {
            lines++;
            cols = 0;
        } else if ((ch & 0xC0) != 0x80) {
            if (++cols > widest) widest = cols;
        }
    }
    *w = widest * ADVANCE * scale;
    *h = lines * LINE_H * scale;
}
