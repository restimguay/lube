enum { CH_OTHER, CH_LETTER, CH_NUMBER, CH_SPACE, CH_END };  /* (CH_END: past the end of the text) */

static int char_class(uint32_t c) {
    if (c < 0x80) {
        if ((c | 32) >= 'a' && (c | 32) <= 'z') return CH_LETTER;
        if (c >= '0' && c <= '9') return CH_NUMBER;
        return c == ' ' || (c >= 9 && c <= 13) ? CH_SPACE : CH_OTHER;
    }
    if (c == 0x85 || c == 0xa0 || c == 0x1680 || (c >= 0x2000 && c <= 0x200a) || c == 0x2028 || c == 0x2029 ||
        c == 0x202f || c == 0x205f || c == 0x3000)
        return CH_SPACE;
    size_t lo = 0, hi = sizeof UNI_RANGES / sizeof UNI_RANGES[0] / 2;
    while (lo < hi) {  /* the first range that ends at c or after it */
        size_t mid = (lo + hi) / 2;
        if (UNI_RANGES[2 * mid + 1] < c) lo = mid + 1;
        else hi = mid;
    }
    if (lo == sizeof UNI_RANGES / sizeof UNI_RANGES[0] / 2 || UNI_RANGES[2 * lo] >> 1 > c) return CH_OTHER;
    return UNI_RANGES[2 * lo] & 1 ? CH_NUMBER : CH_LETTER;
}

/* How many bytes the UTF-8 character starting with byte b has (1 for a byte that starts none). */
static int utf8_len(unsigned char b) { return b < 0xc0 ? 1 : b < 0xe0 ? 2 : b < 0xf0 ? 3 : b < 0xf8 ? 4 : 1; }

/* The character at s (n bytes left), and its length in *len: U+FFFD for bytes that are not UTF-8. */
static uint32_t utf8_get(const unsigned char *s, size_t n, int *len) {
    int k = utf8_len(s[0]);
    if (k == 1 || (size_t)k > n) {
        *len = 1;
        return s[0] < 0x80 ? s[0] : 0xfffd;
    }
    uint32_t c = s[0] & (0x7f >> k);
    for (int i = 1; i < k; i++) {
        if ((s[i] & 0xc0) != 0x80) {
            *len = 1;
            return 0xfffd;
        }
        c = c << 6 | (s[i] & 0x3f);
    }
    *len = k;
    return c;
}

/* Writes character c (below U+0800: byte-level BPE's) as UTF-8 at out: its length. */
static int utf8_put(uint32_t c, unsigned char *out) {
    if (c < 0x80) {
        out[0] = (unsigned char)c;
        return 1;
    }
    out[0] = (unsigned char)(0xc0 | c >> 6);
    out[1] = (unsigned char)(0x80 | (c & 0x3f));
    return 2;
}

/* How many bytes at the end of s[0..n) are the start of a UTF-8 character still to come (0 to 3). */
static size_t utf8_unfinished(const unsigned char *s, size_t n) {
    for (size_t back = 1; back <= 3 && back <= n; back++) {
        unsigned char b = s[n - back];
        if ((b & 0xc0) != 0x80) return b >= 0xc0 && (size_t)utf8_len(b) > back ? back : 0;
    }
    return 0;
}
